//! `web_embed`: a build tool. It copies the console (`web/` and the browser WASM module) into a
//! directory of its own and writes `web_files.zig` there, a table of `@embedFile`s that
//! `zcube-server` imports, so the server is one static binary with the console inside it and `web/`
//! needs no build step. `@embedFile` cannot reach outside its own package, which is why the files
//! are copied beside the table rather than named by path.
//!
//! usage: web_embed <out-dir> <web-dir> <console.wasm>

const std = @import("std");
const assert = std.debug.assert;
const constants = @import("constants.zig");

/// More than the console will ever have; a runaway directory is an error, not a huge binary.
const files_max: u32 = 256;
const file_bytes_max: u32 = 4 * 1024 * 1024;
const wasm_path = "sim/zcube_console.wasm";

/// Files under `web/` that are development tools and not part of the console.
const skipped = [_][]const u8{"mock/gen-codes.mjs"};

const Entry = struct { path: []const u8, bytes: []const u8 };

pub fn main(init: std.process.Init) u8 {
    const arena = init.arena.allocator();
    const args = init.minimal.args.toSlice(arena) catch return constants.exit_user;
    if (args.len != 4) return fail(init.io, "usage: web_embed <out-dir> <web-dir> <console.wasm>");
    run(init, args[1], args[2], args[3]) catch |err| {
        const format = "web_embed: {s}";
        const text = std.fmt.allocPrint(arena, format, .{@errorName(err)}) catch "web_embed";
        return fail(init.io, text);
    };
    return constants.exit_ok;
}

fn fail(io: std.Io, text: []const u8) u8 {
    std.Io.File.stderr().writeStreamingAll(io, text) catch {}; // Nowhere else to report it.
    std.Io.File.stderr().writeStreamingAll(io, "\n") catch {};
    return constants.exit_user;
}

fn run(init: std.process.Init, out_path: []const u8, web_path: []const u8, wasm: []const u8) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    var entries: std.ArrayList(Entry) = .empty;
    var web = try std.Io.Dir.cwd().openDir(io, web_path, .{ .iterate = true });
    defer web.close(io);
    var walker = try web.walk(arena);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        if (entry.basename[0] == '.') continue;
        if (is_skipped(entry.path)) continue;
        if (entries.items.len == files_max) return error.TooManyFiles;
        const path = try arena.dupe(u8, entry.path);
        const limit: std.Io.Limit = .limited(file_bytes_max);
        const bytes = try entry.dir.readFileAlloc(io, entry.basename, arena, limit);
        try entries.append(arena, .{ .path = path, .bytes = bytes });
    }
    const limit: std.Io.Limit = .limited(file_bytes_max);
    const module = try std.Io.Dir.cwd().readFileAlloc(io, wasm, arena, limit);
    try entries.append(arena, .{ .path = wasm_path, .bytes = module });
    std.mem.sort(Entry, entries.items, {}, less_than);
    try write_all(init, out_path, entries.items);
}

fn is_skipped(path: []const u8) bool {
    for (skipped) |name| {
        if (std.mem.eql(u8, path, name)) return true;
    }
    return false;
}

fn less_than(_: void, left: Entry, right: Entry) bool {
    return std.mem.lessThan(u8, left.path, right.path);
}

fn write_all(init: std.process.Init, out_path: []const u8, entries: []const Entry) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    var out = try std.Io.Dir.cwd().openDir(io, out_path, .{});
    defer out.close(io);
    var table: std.Io.Writer.Allocating = .init(arena);
    const writer = &table.writer;
    try writer.writeAll(
        \\//! Generated by web_embed.zig: the console's files, embedded.
        \\pub const File = struct { path: []const u8, content_type: []const u8, bytes: []const u8 };
        \\pub const files = [_]File{
        \\
    );
    for (entries, 0..) |entry, index| {
        const name = try std.fmt.allocPrint(arena, "f{d}", .{index});
        try out.writeFile(io, .{ .sub_path = name, .data = entry.bytes });
        const row = "    .{{ .path = \"{s}\", .content_type = \"{s}\", " ++
            ".bytes = @embedFile(\"{s}\") }},\n";
        try writer.print(row, .{
            entry.path, content_type(entry.path), name,
        });
    }
    try writer.writeAll("};\n");
    try out.writeFile(io, .{ .sub_path = "web_files.zig", .data = table.written() });
}

/// By extension: the types a console made of HTML, CSS, modules, JSON, SVG and WASM needs.
fn content_type(path: []const u8) []const u8 {
    const extension = std.fs.path.extension(path);
    const known = [_]struct { []const u8, []const u8 }{
        .{ ".html", "text/html; charset=utf-8" },
        .{ ".css", "text/css; charset=utf-8" },
        .{ ".js", "text/javascript; charset=utf-8" },
        .{ ".mjs", "text/javascript; charset=utf-8" },
        .{ ".json", "application/json" },
        .{ ".svg", "image/svg+xml" },
        .{ ".wasm", "application/wasm" },
        .{ ".png", "image/png" },
        .{ ".ico", "image/x-icon" },
        .{ ".txt", "text/plain; charset=utf-8" },
        .{ ".md", "text/plain; charset=utf-8" },
    };
    for (known) |pair| {
        if (std.mem.eql(u8, extension, pair[0])) return pair[1];
    }
    return "application/octet-stream";
}
